# ---------- v3 清洗规则（与之前一致） ----------
_EMOJI = re.compile("[\U0001F300-\U0001FAFF\U00002600-\U000027BF"
                    "\U0001F1E0-\U0001F1FF\uFE0F\u200D]+")
_URL   = re.compile(r'(?:https?://|www\.)\S+', re.I)
_AT    = re.compile(r'@[A-Za-z0-9_\u4e00-\u9fa5\-]{1,30}')
_TOPIC = re.compile(r'#([^#\n]{1,30})#')
_MP    = re.compile(r'([!?！？。，,.])\1+')
_NUM   = re.compile(r'\d+(?:\.\d+)?')
_KEEP  = re.compile(r'[^\u4e00-\u9fa5A-Za-z0-9 ]')


def clean_text(text):
    if not isinstance(text, str):
        return ""
    text = unicodedata.normalize('NFKC', text)
    text = _URL.sub(' URLTOKEN ', text)
    text = _AT.sub(' USERTOKEN ', text)
    text = _TOPIC.sub(r' \1 ', text)
    text = _EMOJI.sub(' ', text)
    text = text.replace('\u3000', ' ')
    text = _MP.sub(r'\1', text)
    text = _NUM.sub(' ', text)
    text = _KEEP.sub(' ', text)
    text = text.lower()
    return re.sub(r'\s+', ' ', text).strip()